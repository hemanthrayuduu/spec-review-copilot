"""The exceptions and clarifications letter (spec 8.16), a Word draft for the engineer to finish.

The letterhead is a placeholder, never a real company. Items resting on synthetic evidence say so.
"""

from datetime import date
from pathlib import Path

import docx

from spec_review.review.run_view import Item, RunView

LETTERHEAD = "[Manufacturer name]"
FOOTER = "Draft generated by Spec Review Copilot for engineer review."


def _position(item: Item) -> str:
    text = item.decision.note if item.decision and item.decision.note else (item.result.reason if item.result else "")
    synthetic = " (fictional demo data)" if item.result and item.result.uses_synthetic else ""
    return f"{text}{synthetic}"


def _items(document: docx.document.Document, items: list[Item]) -> None:
    if not items:
        document.add_paragraph("None.")
        return
    for n, it in enumerate(items, start=1):
        r = it.req
        head = document.add_paragraph()
        head.add_run(f"{n}. Section {r.section_number or '-'}, paragraph {r.paragraph_path} "
                     f"({r.doc_id} p.{r.page})").bold = True
        document.add_paragraph(f"The specification requires: “{r.source_text}”")
        document.add_paragraph(f"Our position: {_position(it)}")


def write_letter(view: RunView, path: Path) -> Path:
    package = view.info.package_id if view.info else view.brief.package_id
    document = docx.Document()
    document.add_paragraph().add_run(LETTERHEAD).bold = True
    document.add_heading("Exceptions and Clarifications", level=1)
    document.add_paragraph(f"Project: {package}")
    document.add_paragraph(f"Date: {date.today().isoformat()}")
    if view.draft_banner:
        document.add_paragraph().add_run(view.draft_banner).bold = True
    document.add_paragraph("We have reviewed the bid documents and offer the following exceptions and "
                           "clarifications. All other requirements are accepted as written.")
    document.add_heading("Exceptions", level=2)
    _items(document, [i for i in view.items if i.final_status == "deviation"])
    document.add_heading("Clarifications", level=2)
    _items(document, [i for i in view.items if i.final_status == "comply_with_clarification"])
    document.add_paragraph("Sincerely,")
    document.add_paragraph("[Name], [Title]")
    document.add_paragraph(FOOTER)
    path.parent.mkdir(parents=True, exist_ok=True)
    document.save(str(path))
    return path
